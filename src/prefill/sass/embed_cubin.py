#!/usr/bin/env python3
"""embed_cubin.py hand.cubin out.inc : the cubin as a C array (kCubin / kCubinSize) for src/prefill/gemm_sass.cuh"""
import sys
data = open(sys.argv[1], 'rb').read()
lines = ['// generated by sass/embed_cubin.py from the cubin that sass/gen_hfma.py + sass/build_hand.bat make: %d bytes (do not edit)' % len(data),
         'static const unsigned char kCubin[] = {']
for i in range(0, len(data), 24):
    lines.append('    ' + ','.join('0x%02x' % b for b in data[i:i + 24]) + ',')
lines.append('};')
lines.append('static const size_t kCubinSize = sizeof(kCubin);')
open(sys.argv[2], 'w', newline='\n').write('\n'.join(lines) + '\n')
print('%s: %d bytes' % (sys.argv[2], len(data)))
