#!/usr/bin/env python3
"""writes containers.cu: one empty kernel per generated shape (the signature fixes the parameter layout, the static shared memory
and the special registers the head reads); gen_hfma.py replaces each body's instruction stream."""
import sys
import gen_hfma as g

out = ['// containers.cu - generated by mk_containers.py: the parameter layout of the hand-scheduled GEMMs (bodies replaced by gen_hfma.py)',
       '#include <cstdint>',
       'struct Tab { unsigned v[24]; };']
for sp in g.SPECS:
    z = sp.kind == 'hc'
    if sp.kind == 'dense':
        sig = 'const uint4* __restrict__ X, const uint4* __restrict__ Wt, float* __restrict__ Y, int Tm128'
    elif not sp.split:
        sig = 'const uint4* __restrict__ X, const uint4* __restrict__ Wt, float* __restrict__ Y, const float* __restrict__ yscp, unsigned* __restrict__ badp, int Tm128'
    else:
        sig = 'const uint4* __restrict__ X, const uint4* __restrict__ Wt, float* __restrict__ Y, const float* __restrict__ yscp, unsigned* __restrict__ badp, int Tm128, Tab tab'
    body = ['    __shared__ __align__(16) uint32_t pool[9216];',
            '    uint32_t tid, cx, cy, cz = 0;',
            '    asm volatile("mov.u32 %0, %%tid.x;" : "=r"(tid));',
            '    asm volatile("mov.u32 %0, %%ctaid.x;" : "=r"(cx));',
            '    asm volatile("mov.u32 %0, %%ctaid.y;" : "=r"(cy));']
    if z:
        body.append('    asm volatile("mov.u32 %0, %%ctaid.z;" : "=r"(cz));')
    body += ['    pool[tid] = cx + cy + cz;', '    __syncthreads();']
    if sp.kind == 'dense':
        body.append('    Y[tid + Tm128] = (float) pool[(tid * 7) & 8191] + (float) ((uintptr_t) X + (uintptr_t) Wt);')
    elif not sp.split:
        body.append('    Y[tid + Tm128] = (float) pool[(tid * 7) & 8191] + (float) (uintptr_t) yscp + (float) ((uintptr_t) X + (uintptr_t) Wt); atomicAdd(badp, 1u);')
    else:
        body.append('    Y[tid + Tm128] = (float) pool[(tid * 7) & 8191] + (float) (uintptr_t) yscp + (float) ((uintptr_t) X + (uintptr_t) Wt) + (float) tab.v[tid & 15]; atomicAdd(badp, 1u);')
    out.append('extern "C" __global__ void __launch_bounds__(256, 1) %s(%s) {' % (sp.name, sig))
    out += body
    out.append('}')
open('containers.cu', 'w').write('\n'.join(out) + '\n')
print('containers.cu:', len(g.SPECS), 'kernels')
